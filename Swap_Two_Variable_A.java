// WAP to swap two number with using third variable in the java


public class Swap_Two_Variable_A {

    public static void main(String args [])

        {
            int a = 10 ;
            int b = 20 ;
            int temp ;

            temp = a ;
            a = b ;
            b = temp ;
             

            System.out.println(a);
            System.out.println(b);


        }
    
    
}
