public class Table {

    static void Table1() {   // Method declaration
        for (int i = 1; i <= 10; i++) {
            System.out.println(2 * i);
        }
    }

    public static void main(String args[]) {
        System.out.println("Hi");
        Table1();               // Method Call
        System.out.println("Byy");
    }
}

