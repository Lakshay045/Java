public class Unary {
    
    public static void main(String[] args){

        int a = 10 ;

        a++ ;

        System.out.println("Increment : " + a);

        int b = 15 ; 

        b-- ; 

        System.out.println("Decrement : " + b);

        int c = 10;

        System.out.println(c++);
        System.out.println(c);

        int d = 10;

        System.out.println(++d);
        System.out.println(d);


    }
}
