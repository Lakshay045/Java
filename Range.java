public class Range {

    public static void main(String[] args) {

        System.out.println("\nByte");
        System.out.println("Minimum is : " + Byte.MIN_VALUE);
        System.out.println("Maximum is : " + Byte.MAX_VALUE);

        System.out.println("\nShort");
        System.out.println("Minimum is : " + Short.MIN_VALUE);
        System.out.println("Maximum is : " + Short.MAX_VALUE);

        System.out.println("\nInteger");
        System.out.println("Minimum is : " + Integer.MIN_VALUE);
        System.out.println("Maximum is : " + Integer.MAX_VALUE);

        System.out.println("\nLong");
        System.out.println("Minimum is : " + Long.MIN_VALUE);
        System.out.println("Maximum is : " + Long.MAX_VALUE);

        System.out.println("\nFloat");
        System.out.println("Minimum is : " + Float.MIN_VALUE);
        System.out.println("Maximum is : " + Float.MAX_VALUE);

        System.out.println("\nDouble");
        System.out.println("Minimum is : " + Double.MIN_VALUE);
        System.out.println("Maximum is : " + Double.MAX_VALUE);

        System.out.println("\nCharacter");
        System.out.println("Minimum is : " + (int) Character.MIN_VALUE);
        System.out.println("Maximum is : " + (int) Character.MAX_VALUE);

    }
}